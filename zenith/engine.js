  /* ---------------- formatters ---------------- */
  function raToHMS(raDeg) {
    var hh = wrap360(raDeg) / 15;
    var H = Math.floor(hh), Mn = Math.floor((hh - H) * 60), S = Math.round(((hh - H) * 60 - Mn) * 60);
    if (S === 60) { S = 0; Mn++; }
    if (Mn === 60) { Mn = 0; H = (H + 1) % 24; }
    return H + 'h ' + (Mn < 10 ? '0' : '') + Mn + 'm ' + (S < 10 ? '0' : '') + S + 's';
  }
  function decToDMS(decDeg) {
    var sign = decDeg < 0 ? '−' : '+';
    var a = Math.abs(decDeg);
    var D = Math.floor(a), Mn = Math.round((a - D) * 60);
    if (Mn === 60) { D += 1; Mn = 0; }
    return sign + D + '° ' + (Mn < 10 ? '0' : '') + Mn + '′';
  }
