  /* ---------------- deterministic hashing / text ---------------- */
  function hashStr(s) {
    var h = 0x811c9dc5;
    s = String(s);
    for (var i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0;
    }
    return h >>> 0;
  }
  function escapeHTML(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  /* ---------------- angles & time bases ---------------- */
  function wrap360(d) { return ((d % 360) + 360) % 360; }
  function wrap180(d) { var w = wrap360(d); return w > 180 ? w - 360 : w; }
  function julianDay(ms) { return ms / DAY + 2440587.5; }
  function centuries(ms) { return (julianDay(ms) - 2451545.0) / 36525; }

  // Greenwich MEAN sidereal time, degrees.
  function gmstDeg(ms) {
    var d = julianDay(ms) - 2451545.0;
    var T = d / 36525;
    return wrap360(280.46061837 + 360.98564736629 * d + 0.000387933 * T * T - T * T * T / 38710000);
  }

  // Nutation in longitude and obliquity (Meeus ch. 22, principal terms —
  // good to ~0.5", far below chart needs but it keeps apparent ST honest).
  function nutation(ms) {
    var T = centuries(ms);
    var Om = (125.04452 - 1934.136261 * T) * DEG;
    var L = (280.4665 + 36000.7698 * T) * DEG;
    var Lp = (218.3165 + 481267.8813 * T) * DEG;
    var dpsi = (-17.20 * Math.sin(Om) - 1.32 * Math.sin(2 * L) - 0.23 * Math.sin(2 * Lp) + 0.21 * Math.sin(2 * Om)) / 3600;
    var deps = (9.20 * Math.cos(Om) + 0.57 * Math.cos(2 * L) + 0.10 * Math.cos(2 * Lp) - 0.09 * Math.cos(2 * Om)) / 3600;
    return { dpsiDeg: dpsi, depsDeg: deps };
  }

  function obliquityDeg(ms) {           // mean obliquity
    var T = centuries(ms);
    return 23.4392911 - 0.0130042 * T - 1.64e-7 * T * T + 5.04e-7 * T * T * T;
  }
  function trueObliquityDeg(ms) { return obliquityDeg(ms) + nutation(ms).depsDeg; }

  // Apparent sidereal time = mean + equation of the equinoxes.
  function gastDeg(ms) {
    var n = nutation(ms);
    return wrap360(gmstDeg(ms) + n.dpsiDeg * Math.cos(trueObliquityDeg(ms) * DEG));
  }
  function lstDeg(lon, ms) { return wrap360(gastDeg(ms) + (Number(lon) || 0)); }

  // Ecliptic (λ, β) of date → equatorial (RA, Dec) of date.
  function eclToEq(lambda, beta, ms) {
    var e = trueObliquityDeg(ms) * DEG, l = lambda * DEG, b = beta * DEG;
    var sinDec = Math.sin(b) * Math.cos(e) + Math.cos(b) * Math.sin(e) * Math.sin(l);
    var y = Math.sin(l) * Math.cos(e) - Math.tan(b) * Math.sin(e);
    return {
      raDeg: wrap360(Math.atan2(y, Math.cos(l)) / DEG),
      decDeg: Math.asin(Math.max(-1, Math.min(1, sinDec))) / DEG
    };
  }

  // Rigorous precession of a J2000.0 position to the equator of date
  // (IAU 1976 three-rotation form, Meeus ch. 21).
  function precessJ2000(raDeg, decDeg, ms) {
    var T = centuries(ms);
    var zeta = (2306.2181 * T + 0.30188 * T * T + 0.017998 * T * T * T) / 3600 * DEG;
    var z = (2306.2181 * T + 1.09468 * T * T + 0.018203 * T * T * T) / 3600 * DEG;
    var theta = (2004.3109 * T - 0.42665 * T * T - 0.041833 * T * T * T) / 3600 * DEG;
    var ra = raDeg * DEG, dec = decDeg * DEG;
    var A = Math.cos(dec) * Math.sin(ra + zeta);
    var B = Math.cos(theta) * Math.cos(dec) * Math.cos(ra + zeta) - Math.sin(theta) * Math.sin(dec);
    var C = Math.sin(theta) * Math.cos(dec) * Math.cos(ra + zeta) + Math.cos(theta) * Math.sin(dec);
    return {
      raDeg: wrap360((z + Math.atan2(A, B)) / DEG),
      decDeg: Math.asin(Math.max(-1, Math.min(1, C))) / DEG
    };
  }

  // Equatorial → horizontal. Azimuth from north through east.
  function altAz(raDeg, decDeg, lat, lon, ms) {
    var H = (lstDeg(lon, ms) - raDeg) * DEG;
    var phi = (Number(lat) || 0) * DEG, dec = decDeg * DEG;
    var sinAlt = Math.sin(phi) * Math.sin(dec) + Math.cos(phi) * Math.cos(dec) * Math.cos(H);
    var alt = Math.asin(Math.max(-1, Math.min(1, sinAlt)));
    var az = Math.atan2(Math.sin(H), Math.cos(H) * Math.sin(phi) - Math.tan(dec) * Math.cos(phi)) / DEG + 180;
    return { altDeg: alt / DEG, azDeg: wrap360(az) };
  }

  // Bennett's refraction: how much higher a body APPEARS, in degrees,
  // given its true altitude. ~34' at the horizon, ~1' at 45°.
  function refractionDeg(altDeg) {
    if (altDeg < -1) return 0;
    var R = 1 / Math.tan((altDeg + 7.31 / (altDeg + 4.4)) * DEG); // arcminutes
    return R / 60;
  }

  // Great-circle separation between two equatorial positions, degrees.
  function separationDeg(ra1, dec1, ra2, dec2) {
    var a1 = ra1 * DEG, d1 = dec1 * DEG, a2 = ra2 * DEG, d2 = dec2 * DEG;
    var c = Math.sin(d1) * Math.sin(d2) + Math.cos(d1) * Math.cos(d2) * Math.cos(a1 - a2);
    return Math.acos(Math.max(-1, Math.min(1, c))) / DEG;
  }

  /* ---------------- the sun ---------------- */
  // Low-precision apparent solar position (Astronomical Almanac): ~0.01°,
  // aberration folded in. Verified against Meeus example 25.a in the tests.
  function sunPosition(ms) {
    var n = julianDay(ms) - 2451545.0;
    var L = wrap360(280.460 + 0.9856474 * n);
    var g = wrap360(357.528 + 0.9856003 * n) * DEG;
    var lambda = wrap360(L + 1.915 * Math.sin(g) + 0.020 * Math.sin(2 * g));
    var dist = 1.00014 - 0.01671 * Math.cos(g) - 0.00014 * Math.cos(2 * g);
    var eq = eclToEq(lambda, 0, ms);
    return { lambdaDeg: lambda, raDeg: eq.raDeg, decDeg: eq.decDeg, distAU: dist };
  }
  function sunAltAz(lat, lon, ms) {
    var s = sunPosition(ms);
    return altAz(s.raDeg, s.decDeg, lat, lon, ms);
  }

