  function planetGeo(key, ms) {
    var p = heliocentric(key, ms), earth = heliocentric('earth', ms);
    var gx = p.x - earth.x, gy = p.y - earth.y, gz = p.z - earth.z;
    var delta = Math.sqrt(gx * gx + gy * gy + gz * gz);
    var lambda = wrap360(Math.atan2(gy, gx) / DEG);
    var beta = Math.asin(gz / delta) / DEG;
    var eq = eclToEq(lambda, beta, ms);
    var sunLambda = sunPosition(ms).lambdaDeg;
    var elong = wrap180(lambda - sunLambda);
    var R = earth.r;
    var cosPhase = (p.r * p.r + delta * delta - R * R) / (2 * p.r * delta);
    var phaseAngle = Math.acos(Math.max(-1, Math.min(1, cosPhase))) / DEG;
    return {
      key: key, raDeg: eq.raDeg, decDeg: eq.decDeg,
      distAU: delta, sunDistAU: p.r,
      elongationDeg: elong, phaseAngleDeg: phaseAngle,
      illumination: (1 + Math.cos(phaseAngle * DEG)) / 2,
      magnitude: Math.round(MAG[key](p.r, delta, phaseAngle) * 10) / 10
    };
  }

  /* ---------------- Galilean satellites (Meeus ch. 44, low accuracy) ---------------- */
  // Apparent X offsets of Io, Europa, Ganymede and Callisto from Jupiter's
  // centre, in Jupiter equatorial radii. X > 0 is WEST of the planet (the
  // classic almanac convention); |X| at greatest elongation ≈ 5.9 / 9.4 /
  // 15.0 / 26.4. Y (north-south) is small and omitted — this is the strip
  // view every observing guide prints.
  var GALILEAN = [
    { key: 'io', name: 'Io', period: 1.769138 },
    { key: 'europa', name: 'Europa', period: 3.551181 },
    { key: 'ganymede', name: 'Ganymede', period: 7.154553 },
    { key: 'callisto', name: 'Callisto', period: 16.689018 }
  ];
  function galileanMoons(ms) {
    var d = julianDay(ms) - 2451545.0;
    var V = wrap360(172.74 + 0.00111588 * d) * DEG;
    var M = wrap360(357.529 + 0.9856003 * d) * DEG;
    var N = wrap360(20.020 + 0.0830853 * d + 0.329 * Math.sin(V)) * DEG;
    var J = wrap360(66.115 + 0.9025179 * d - 0.329 * Math.sin(V)) * DEG;
    var A = 1.915 * Math.sin(M) + 0.020 * Math.sin(2 * M);
    var B = 5.555 * Math.sin(N) + 0.168 * Math.sin(2 * N);
    var K = (J / DEG + A - B) * DEG;
    var R = 1.00014 - 0.01671 * Math.cos(M) - 0.00014 * Math.cos(2 * M);
    var r = 5.20872 - 0.25208 * Math.cos(N) - 0.00611 * Math.cos(2 * N);
    var Delta = Math.sqrt(r * r + R * R - 2 * r * R * Math.cos(K));
    var psi = Math.asin(Math.max(-1, Math.min(1, R / Delta * Math.sin(K)))) / DEG;
    var dd = d - Delta / 173;
    var u1 = wrap360(163.8069 + 203.4058646 * dd + psi - B);
    var u2 = wrap360(358.4140 + 101.2916335 * dd + psi - B);
    var u3 = wrap360(5.7176 + 50.2345180 * dd + psi - B);
    var u4 = wrap360(224.8092 + 21.4879800 * dd + psi - B);
    var G = wrap360(331.18 + 50.310482 * dd) * DEG;
    var H = wrap360(87.45 + 21.569231 * dd) * DEG;
    u1 += 0.473 * Math.sin(2 * (u1 - u2) * DEG);
    u2 += 1.065 * Math.sin(2 * (u2 - u3) * DEG);
    u3 += 0.165 * Math.sin(G);
    u4 += 0.843 * Math.sin(H);
    var r1 = 5.9057 - 0.0244 * Math.cos(2 * (u1 - u2) * DEG);
    var r2 = 9.3966 - 0.0882 * Math.cos(2 * (u2 - u3) * DEG);
    var r3 = 14.9883 - 0.0216 * Math.cos(G);
    var r4 = 26.3627 - 0.1939 * Math.cos(H);
    var us = [u1, u2, u3, u4], rs = [r1, r2, r3, r4];
    var out = [];
    for (var i = 0; i < 4; i++) {
      out.push({
        key: GALILEAN[i].key, name: GALILEAN[i].name, period: GALILEAN[i].period,
        x: rs[i] * Math.sin(us[i] * DEG),          // + west, in Jupiter radii
        front: Math.cos(us[i] * DEG) > 0 ? false : true, // true = nearer to us than Jupiter
        maxElong: rs[i]
      });
    }
    return out;
  }

  /* ---------------- rise, set & twilight ---------------- */
  function riseSet(altFn, horizonDeg, startMs) {
    var STEP = 10 * MINUTE;
    var events = [];
    var prev = altFn(startMs) - horizonDeg;
    var maxAlt = prev + horizonDeg, maxAt = startMs;
    for (var t = startMs + STEP; t <= startMs + DAY; t += STEP) {
      var cur = altFn(t) - horizonDeg;
      if (cur + horizonDeg > maxAlt) { maxAlt = cur + horizonDeg; maxAt = t; }
      if ((prev <= 0 && cur > 0) || (prev > 0 && cur <= 0)) {
        var lo = t - STEP, hi = t;
        for (var i = 0; i < 20; i++) {
          var mid = (lo + hi) / 2;
          if (((altFn(mid) - horizonDeg) > 0) === (cur > 0)) hi = mid; else lo = mid;
        }
        events.push({ type: cur > 0 ? 'rise' : 'set', ms: Math.round((lo + hi) / 2) });
      }
      prev = cur;
    }
    var rise = null, set = null;
    for (var j = 0; j < events.length; j++) {
      if (events[j].type === 'rise' && rise === null) rise = events[j].ms;
      if (events[j].type === 'set' && set === null) set = events[j].ms;
    }
    return {
      rise: rise, set: set,
      alwaysUp: events.length === 0 && prev > 0,
      alwaysDown: events.length === 0 && prev <= 0,
      transit: maxAt, transitAltDeg: maxAlt
    };
  }

  function sunTimes(lat, lon, startMs) {
    var alt = function (t) { return sunAltAz(lat, lon, t).altDeg; };
    var day = riseSet(alt, -0.833, startMs);
    var civil = riseSet(alt, -6, startMs);
    var nautical = riseSet(alt, -12, startMs);
    var astro = riseSet(alt, -18, startMs);
    return {
      sunrise: day.rise, sunset: day.set,
      civilDawn: civil.rise, civilDusk: civil.set,
      nauticalDawn: nautical.rise, nauticalDusk: nautical.set,
      astroDawn: astro.rise, astroDusk: astro.set,
      solarNoon: day.transit, noonAltDeg: Math.round(day.transitAltDeg * 10) / 10,
      dayLengthMs: (day.rise !== null && day.set !== null)
        ? (day.set > day.rise ? day.set - day.rise : day.set - day.rise + DAY) : null,
      midnightSun: day.alwaysUp, polarNight: day.alwaysDown
    };
  }

  function moonTimes(lat, lon, startMs) {
    var alt = function (t) { return moonAltAz(lat, lon, t).altDeg; };
    var r = riseSet(alt, -0.566, startMs); // upper limb + refraction, topocentric
    return { moonrise: r.rise, moonset: r.set, alwaysUp: r.alwaysUp, alwaysDown: r.alwaysDown, transit: r.transit };
  }

  /* ---------------- catalog access ---------------- */
  function starCount() { var c = catalog(); return c ? c.STAR_COUNT : 0; }
  // One star by index: J2000 catalog position plus labels.
  function star(i) {
    var c = catalog();
    if (!c || i < 0 || i >= c.STAR_COUNT) return null;
    var o = i * c.STAR_STRIDE;
    return {
      i: i, ra: c.STARS[o], dec: c.STARS[o + 1], mag: c.STARS[o + 2], ci: c.STARS[o + 3],
      con: c.STARS[o + 4] >= 0 ? c.CONS[c.STARS[o + 4]] : '',
      name: c.STAR_NAMES[i] || '', desig: c.STAR_DESIGS[i] || ''
    };
  }
  function namedStars() {
    var c = catalog(), out = [];
    if (!c) return out;
    for (var k in c.STAR_NAMES) out.push(star(+k));
    out.sort(function (a, b) { return a.mag - b.mag; });
    return out;
  }
  function starByName(name) {
    var c = catalog();
    if (!c) return null;
    var q = String(name || '').toLowerCase();
    for (var k in c.STAR_NAMES) if (c.STAR_NAMES[k].toLowerCase() === q) return star(+k);
    return null;
  }
  function dsoById(id) {
    var c = catalog();
    if (!c) return null;
    for (var i = 0; i < c.DSOS.length; i++) if (c.DSOS[i].id === id) return c.DSOS[i];
    return null;
  }

  /* ---------------- search: one box for the whole sky ---------------- */
  function searchObjects(query, limit) {
    var c = catalog();
    var q = String(query || '').trim().toLowerCase();
    if (!q) return [];
    limit = limit || 12;
    var out = [];
    function push(score, item) { out.push({ score: score, item: item }); }
    // planets + moon + sun
    var SOLAR = [{ kind: 'moon', name: 'Moon' }, { kind: 'sun', name: 'Sun' }];
    for (var p = 0; p < PLANETS.length; p++) SOLAR.push({ kind: 'planet', key: PLANETS[p].key, name: PLANETS[p].name });
    for (var s = 0; s < SOLAR.length; s++) {
      var n = SOLAR[s].name.toLowerCase();
      if (n === q) push(100, SOLAR[s]);
      else if (n.indexOf(q) === 0) push(80, SOLAR[s]);
    }
    if (c) {
      // DSOs: by id (m31, ngc 224) or name
      for (var d = 0; d < c.DSOS.length; d++) {
        var dso = c.DSOS[d];
        var id = dso.id.toLowerCase(), nm = (dso.name || '').toLowerCase(), dg = (dso.desig || '').toLowerCase();
        var score = 0;
        if (id === q || dg === q || nm === q) score = 95;
        else if (id === q.replace(/\s+/g, '')) score = 95;
        else if (id.indexOf(q) === 0 || dg.indexOf(q.replace(/\s+/g, ' ')) === 0) score = 70;
        else if (nm.indexOf(q) === 0) score = 65;
        else if (nm.indexOf(q) !== -1 && q.length >= 3) score = 40;
        if (score) push(score - dso.mag / 30, { kind: 'dso', id: dso.id, name: dso.name, dso: dso });
      }
      // named stars + designations
      for (var k in c.STAR_NAMES) {
        var sn = c.STAR_NAMES[k].toLowerCase();
        var sc = sn === q ? 98 : sn.indexOf(q) === 0 ? 68 : (sn.indexOf(q) !== -1 && q.length >= 3) ? 38 : 0;
        if (sc) push(sc, { kind: 'star', i: +k, name: c.STAR_NAMES[k], star: star(+k) });
      }
      for (var k2 in c.STAR_DESIGS) {
        var ds = c.STAR_DESIGS[k2].toLowerCase();
        if (ds === q || ds.replace(/\s+/g, '') === q.replace(/\s+/g, '')) {
          push(90, { kind: 'star', i: +k2, name: c.STAR_DESIGS[k2], star: star(+k2) });
        }
      }
    }
    out.sort(function (a, b) { return b.score - a.score; });
    var seen = {}, res = [];
    for (var o = 0; o < out.length && res.length < limit; o++) {
      var key = out[o].item.kind + ':' + (out[o].item.id || out[o].item.i || out[o].item.key || out[o].item.name);
      if (!seen[key]) { seen[key] = 1; res.push(out[o].item); }
    }
    return res;
  }

  /* ---------------- the chart ---------------- */
  // Zenith-centred azimuthal equidistant; east LEFT (charts are held overhead).
  function project(altDeg, azDeg) {
    var r = (90 - altDeg) / 90;
    var az = azDeg * DEG;
    return { x: -r * Math.sin(az), y: -r * Math.cos(az) };
  }

  // Everything plottable from one spot at one instant. Catalog positions
  // are precessed J2000→date once per call (the precession rotation is
  // identical for every star at a given instant, so it's computed once).
  function skyChart(lat, lon, ms, opts) {
    opts = opts || {};
    var magLimit = opts.magLimit == null ? 5.5 : opts.magLimit;
    var dsoMagLimit = opts.dsoMagLimit == null ? 8.5 : opts.dsoMagLimit;
    var minAlt = opts.minAltDeg == null ? -0.5 : opts.minAltDeg;
    var refract = opts.refraction !== false;
    var c = catalog();

    // precession rotation, once
    var T = centuries(ms);
    var zeta = (2306.2181 * T + 0.30188 * T * T + 0.017998 * T * T * T) / 3600 * DEG;
    var z = (2306.2181 * T + 1.09468 * T * T + 0.018203 * T * T * T) / 3600 * DEG;
    var theta = (2004.3109 * T - 0.42665 * T * T - 0.041833 * T * T * T) / 3600 * DEG;
    var ct = Math.cos(theta), st = Math.sin(theta);
    var lst = lstDeg(lon, ms);
    var phi = (Number(lat) || 0) * DEG, sphi = Math.sin(phi), cphi = Math.cos(phi);

    function place(raJ2000, decJ2000) {
      var ra = raJ2000 * DEG, dec = decJ2000 * DEG;
      var cosd = Math.cos(dec), sind = Math.sin(dec);
      var A = cosd * Math.sin(ra + zeta);
      var B = ct * cosd * Math.cos(ra + zeta) - st * sind;
      var C = st * cosd * Math.cos(ra + zeta) + ct * sind;
      var raD = z + Math.atan2(A, B);                      // radians, of date
      var H = lst * DEG - raD;
      var sinAlt = sphi * C + cphi * Math.sqrt(1 - C * C) * Math.cos(H) * (1); // cos(dec')≈sqrt(1-C²)
      var alt = Math.asin(Math.max(-1, Math.min(1, sinAlt))) / DEG;
      if (refract && alt > -1) alt += refractionDeg(alt);
      var decD = Math.asin(Math.max(-1, Math.min(1, C)));
      var az = Math.atan2(Math.sin(H), Math.cos(H) * sphi - Math.tan(decD) * cphi) / DEG + 180;
      return { altDeg: alt, azDeg: wrap360(az), raDate: wrap360(raD / DEG), decDate: decD / DEG };
    }

    var stars = [];
    if (c) {
      var n = c.STAR_COUNT, stride = c.STAR_STRIDE, arr = c.STARS;
      for (var i = 0; i < n; i++) {
        var o = i * stride;
        var mag = arr[o + 2];
        if (mag > magLimit) break;                        // sorted by magnitude
        var pos = place(arr[o], arr[o + 1]);
        if (pos.altDeg < minAlt) continue;
        var pr = project(pos.altDeg, pos.azDeg);
        stars.push({ i: i, mag: mag, ci: arr[o + 3],
          name: c.STAR_NAMES[i] || '', desig: c.STAR_DESIGS[i] || '',
          con: arr[o + 4] >= 0 ? c.CONS[arr[o + 4]] : '',
          altDeg: pos.altDeg, azDeg: pos.azDeg, x: pr.x, y: pr.y });
      }
    }

    var lines = [];
    if (c && opts.lines !== false) {
      for (var f = 0; f < c.FIGURES.length; f++) {
        var fig = c.FIGURES[f];
        for (var pl = 0; pl < fig.lines.length; pl++) {
          var poly = fig.lines[pl];
          var prev = null;
          for (var v = 0; v < poly.length; v++) {
            var pp = place(poly[v][0], poly[v][1]);
            var cur = pp.altDeg >= minAlt ? project(pp.altDeg, pp.azDeg) : null;
            if (prev && cur) lines.push({ con: fig.id, x1: prev.x, y1: prev.y, x2: cur.x, y2: cur.y });
            prev = cur;
          }
        }
      }
    }

    var dsos = [];
    if (c && opts.dsos !== false) {
      for (var dI = 0; dI < c.DSOS.length; dI++) {
        var dso = c.DSOS[dI];
        if (dso.mag > dsoMagLimit) continue;
        var dp = place(dso.ra, dso.dec);
        if (dp.altDeg < minAlt) continue;
        var dpr = project(dp.altDeg, dp.azDeg);
        dsos.push({ id: dso.id, name: dso.name, type: dso.type, mag: dso.mag,
          altDeg: dp.altDeg, azDeg: dp.azDeg, x: dpr.x, y: dpr.y });
      }
    }

    var planets = [];
    for (var q = 0; q < PLANETS.length; q++) {
      var meta = PLANETS[q];
      var g = planetGeo(meta.key, ms);
      var paa = altAz(g.raDeg, g.decDeg, lat, lon, ms);
      if (refract && paa.altDeg > -1) paa = { altDeg: paa.altDeg + refractionDeg(paa.altDeg), azDeg: paa.azDeg };
      if (paa.altDeg < minAlt) continue;
      var ppr = project(paa.altDeg, paa.azDeg);
      planets.push({ key: meta.key, name: meta.name, emoji: meta.emoji, color: meta.color,
        mag: g.magnitude, altDeg: paa.altDeg, azDeg: paa.azDeg, x: ppr.x, y: ppr.y });
    }

    var maa = moonAltAz(lat, lon, ms);
    var mpr = project(maa.altDeg, maa.azDeg);
    var phase = moonPhase(ms);
    var sun = sunAltAz(lat, lon, ms);
    var spr = project(sun.altDeg, sun.azDeg);

    // equatorial grid (declination circles + hour circles), pre-projected
    var grid = [];
    if (opts.grid) {
      var gd, gh, gpp, gprev;
      for (gd = -60; gd <= 60; gd += 30) {               // dec circles
        gprev = null;
        for (gh = 0; gh <= 360; gh += 5) {
          gpp = place(gh, gd);
          var gc = gpp.altDeg >= minAlt ? project(gpp.altDeg, gpp.azDeg) : null;
          if (gprev && gc) grid.push({ x1: gprev.x, y1: gprev.y, x2: gc.x, y2: gc.y });
          gprev = gc;
        }
      }
      for (gh = 0; gh < 360; gh += 30) {                 // hour circles
        gprev = null;
        for (gd = -85; gd <= 85; gd += 5) {
          gpp = place(gh, gd);
          var gc2 = gpp.altDeg >= minAlt ? project(gpp.altDeg, gpp.azDeg) : null;
          if (gprev && gc2) grid.push({ x1: gprev.x, y1: gprev.y, x2: gc2.x, y2: gc2.y });
          gprev = gc2;
        }
      }
    }

    return {
      stars: stars, lines: lines, dsos: dsos, planets: planets, grid: grid,
      moon: { altDeg: maa.altDeg, azDeg: maa.azDeg, x: mpr.x, y: mpr.y, up: maa.altDeg >= minAlt,
              illumination: phase.illumination, emoji: phase.emoji, name: phase.name, waxing: phase.waxing },
      sun: { altDeg: sun.altDeg, azDeg: sun.azDeg, x: spr.x, y: spr.y, up: sun.altDeg >= -0.833 },
      lstDeg: lst,
      darkness: sun.altDeg >= 0 ? 0 : Math.min(1, -sun.altDeg / 18)
    };
  }

  /* ---------------- observation planning ---------------- */
  var BORTLE = [
    null,
    { nelm: 7.8, label: 'Excellent dark site' },
    { nelm: 7.3, label: 'Truly dark site' },
    { nelm: 6.8, label: 'Rural sky' },
    { nelm: 6.3, label: 'Rural/suburban' },
    { nelm: 5.8, label: 'Suburban sky' },
    { nelm: 5.2, label: 'Bright suburban' },
    { nelm: 4.7, label: 'Suburban/urban' },
    { nelm: 4.2, label: 'City sky' },
    { nelm: 3.6, label: 'Inner city' }
  ];
  function limitingMagnitude(bortle) {
    var b = Math.max(1, Math.min(9, bortle | 0));
    return BORTLE[b].nelm;
  }

  // Altitude of a fixed J2000 position (or the moon / a planet) across a
  // window — the curve every planning app draws.
  function altitudeCurve(target, lat, lon, startMs, hours, stepMin) {
    hours = hours || 14; stepMin = stepMin || 15;
    var pts = [];
    for (var t = startMs; t <= startMs + hours * HOUR; t += stepMin * MINUTE) {
      var alt;
      if (target.kind === 'moon') alt = moonAltAz(lat, lon, t).altDeg;
      else if (target.kind === 'planet') {
        var g = planetGeo(target.key, t);
        alt = altAz(g.raDeg, g.decDeg, lat, lon, t).altDeg;
      } else if (target.kind === 'sun') alt = sunAltAz(lat, lon, t).altDeg;
      else {
        var p = precessJ2000(target.ra, target.dec, t);
        alt = altAz(p.raDeg, p.decDeg, lat, lon, t).altDeg;
      }
      pts.push({ ms: t, altDeg: alt, sunAltDeg: sunAltAz(lat, lon, t).altDeg });
    }
    return pts;
  }

  // Rank tonight's targets the way a planner does: highest dark-sky
  // altitude, brightness against the site's limiting magnitude, and how
  // badly the moon interferes. Deterministic; `ms` anchors the night.
  function tonightTargets(lat, lon, ms, opts) {
    opts = opts || {};
    var bortle = opts.bortle || 4;
    var limit = opts.limit || 12;
    var c = catalog();
    var st = sunTimes(lat, lon, ms);
    var darkStart = st.astroDusk || st.nauticalDusk || st.civilDusk || st.sunset || ms;
    var darkEnd = st.astroDawn || st.nauticalDawn || st.civilDawn || st.sunrise || (ms + 12 * HOUR);
    if (darkEnd <= darkStart) darkEnd += DAY;
    var nelm = limitingMagnitude(bortle);
    var moonUpPhase = moonPhase(darkStart + (darkEnd - darkStart) / 2);
    var out = [];

    function windowScan(altFn) {
      var best = { altDeg: -90, ms: darkStart }, hoursAbove30 = 0;
      for (var t = darkStart; t <= darkEnd; t += 20 * MINUTE) {
        var a = altFn(t);
        if (a > best.altDeg) best = { altDeg: a, ms: t };
        if (a >= 30) hoursAbove30 += 1 / 3;
      }
      return { best: best, hoursAbove30: Math.round(hoursAbove30 * 10) / 10 };
    }

    if (c) {
      var midMoon = moonPosition(darkStart + (darkEnd - darkStart) / 2);
      for (var i = 0; i < c.DSOS.length; i++) {
        var dso = c.DSOS[i];
        if (dso.mag > nelm + 3.5) continue;          // beyond a modest scope at this site
        var scan = windowScan(function (t) {
          var p = precessJ2000(dso.ra, dso.dec, t);
          return altAz(p.raDeg, p.decDeg, lat, lon, t).altDeg;
        });
        if (scan.best.altDeg < 25) continue;
        var moonSep = separationDeg(dso.ra, dso.dec, midMoon.raDeg, midMoon.decDeg);
        var moonPenalty = moonUpPhase.illumination > 0.25 && moonSep < 60
          ? 1 - (0.6 * moonUpPhase.illumination * (1 - moonSep / 60)) : 1;
        var altScore = Math.min(1, scan.best.altDeg / 70);
        var ease = Math.max(0.15, 1 - Math.max(0, dso.mag - 4) / 8);
        var score = altScore * ease * moonPenalty;
        out.push({
          kind: 'dso', id: dso.id, name: dso.name, type: dso.type, mag: dso.mag,
          typeName: (c.DSO_TYPES && c.DSO_TYPES[dso.type]) || 'Deep-sky object',
          bestAltDeg: Math.round(scan.best.altDeg), bestMs: scan.best.ms,
          bestAz: compass(altAz(precessJ2000(dso.ra, dso.dec, scan.best.ms).raDeg,
            precessJ2000(dso.ra, dso.dec, scan.best.ms).decDeg, lat, lon, scan.best.ms).azDeg),
          hoursAbove30: scan.hoursAbove30,
          moonSepDeg: Math.round(moonSep),
          score: Math.round(score * 1000) / 1000
        });
      }
    }
    for (var pq = 0; pq < PLANETS.length; pq++) {
      var meta = PLANETS[pq];
      var scanP = windowScan(function (t) {
        var g = planetGeo(meta.key, t);
        return altAz(g.raDeg, g.decDeg, lat, lon, t).altDeg;
      });
      if (scanP.best.altDeg < 10) continue;
      var gBest = planetGeo(meta.key, scanP.best.ms);
      out.push({
        kind: 'planet', id: meta.key, name: meta.name, type: 'planet', typeName: 'Planet',
        mag: gBest.magnitude, bestAltDeg: Math.round(scanP.best.altDeg), bestMs: scanP.best.ms,
        bestAz: compass(altAz(gBest.raDeg, gBest.decDeg, lat, lon, scanP.best.ms).azDeg),
        hoursAbove30: scanP.hoursAbove30, moonSepDeg: null,
        score: Math.min(1, scanP.best.altDeg / 70) * 1.15   // planets shrug off moonlight
      });
    }
    out.sort(function (a, b) { return b.score - a.score || a.mag - b.mag; });
    return {
      darkStart: darkStart, darkEnd: darkEnd,
      limitingMag: nelm, bortle: bortle, bortleLabel: BORTLE[Math.max(1, Math.min(9, bortle | 0))].label,
      moonIllumination: moonUpPhase.illumination,
      targets: out.slice(0, limit)
    };
  }

  /* ---------------- the evening briefing (kept from v1, topocentric now) ---------------- */
  function tonight(lat, lon, ms) {
    var st = sunTimes(lat, lon, ms);
    var mt = moonTimes(lat, lon, ms);
    var phase = moonPhase(ms);
    var darkStart = st.astroDusk || st.nauticalDusk || st.civilDusk || st.sunset;
    var windowStart = darkStart !== null && darkStart !== undefined ? darkStart : ms;
    var windowLen = DAY / 2;
    var planets = [];
    for (var i = 0; i < PLANETS.length; i++) {
      var meta = PLANETS[i];
      var best = null;
      for (var t = windowStart; t <= windowStart + windowLen; t += 30 * MINUTE) {
        if (sunAltAz(lat, lon, t).altDeg > -6) continue;
        var g = planetGeo(meta.key, t);
        var aa = altAz(g.raDeg, g.decDeg, lat, lon, t);
        if (aa.altDeg < 5) continue;
        if (!best || aa.altDeg > best.altDeg) {
          best = { altDeg: aa.altDeg, azDeg: aa.azDeg, ms: t, mag: g.magnitude, elongationDeg: g.elongationDeg };
        }
      }
      planets.push({
        key: meta.key, name: meta.name, emoji: meta.emoji, color: meta.color,
        visible: !!best, best: best,
        note: best
          ? meta.name + ' up to ' + Math.round(best.altDeg) + '° in the ' + compass(best.azDeg) + ', mag ' + best.mag
          : meta.name + ' is lost in the sun’s glare tonight'
      });
    }
    var visible = planets.filter(function (p) { return p.visible; });
    var moonVerdict;
    if (phase.illumination < 0.15) moonVerdict = 'Dark skies — the Milky Way and faint galaxies are on.';
    else if (phase.illumination < 0.6) moonVerdict = 'Some moonlight; bright targets still shine through.';
    else moonVerdict = 'A bright moon washes out faint targets — chase planets, doubles and the moon itself.';
    return {
      sun: st, moon: mt, phase: phase, planets: planets,
      visibleCount: visible.length,
      moonVerdict: moonVerdict,
      polarNote: st.midnightSun ? 'The sun never sets today — no true night at this latitude.'
        : st.polarNight ? 'The sun never rises today — the sky stays dark around the clock.' : null
    };
  }

