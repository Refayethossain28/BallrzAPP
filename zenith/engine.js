  // Topocentric altitude: the moon is close enough that where you STAND
  // on Earth shifts it by up to a degree — subtract parallax-in-altitude.
  function moonAltAz(lat, lon, ms) {
    var moon = moonPosition(ms);
    var aa = altAz(moon.raDeg, moon.decDeg, lat, lon, ms);
    var topoAlt = aa.altDeg - moon.parallaxDeg * Math.cos(aa.altDeg * DEG);
    return { altDeg: topoAlt, azDeg: aa.azDeg, geocentricAltDeg: aa.altDeg, distKm: moon.distKm };
  }

