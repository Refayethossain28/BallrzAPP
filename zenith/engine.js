  /* ---------------- polar alignment ---------------- */
  // Where Polaris sits on a polar-scope reticle right now. Position angle
  // is measured from 12 o'clock (up, toward the zenith) going CLOCKWISE as
  // seen through an INVERTING polar scope — the SkyWatcher/iOptron dial
  // convention. Uses Polaris precessed to date, so the NCP separation
  // shrinks year by year exactly as it really does (~0.65° in 2026).
  function polarisClock(lat, lon, ms) {
    var J2000_RA = 37.9546, J2000_DEC = 89.2641; // α UMi, J2000
    var p = precessJ2000(J2000_RA, J2000_DEC, ms);
    var haDeg = wrap180(lstDeg(lon, ms) - p.raDeg);
    // As seen on the sky looking at the NCP, Polaris lies at position angle
    // (from north, through the direction of decreasing HA). In an inverting
    // scope the view is rotated 180°: HA 0 → Polaris below the pole → "6".
    var dialDeg = wrap360(180 + haDeg);
    var clockH = dialDeg / 30;                      // 30° per dial hour
    var h = Math.floor(clockH) || 12;
    var mclock = Math.round((clockH - Math.floor(clockH)) * 60);
    if (mclock === 60) { h = (h % 12) + 1; mclock = 0; }
    return {
      haHours: Math.round(haDeg / 15 * 100) / 100,
      sepDeg: Math.round(separationDeg(p.raDeg, p.decDeg, 0, 90) * 1000) / 1000,
      dialDeg: Math.round(dialDeg * 10) / 10,
      clock: h + ':' + (mclock < 10 ? '0' : '') + mclock,
      visible: lat > 0,
      altDeg: altAz(p.raDeg, p.decDeg, lat, lon, ms).altDeg
    };
  }

  /* ---------------- imaging & eyepiece calculators ---------------- */
  // Field of view and sampling for a camera on a telescope — the numbers
  // every astrophotographer checks before framing a target.
  function fovCalc(opts) {
    var f = Number(opts.focalMm), w = Number(opts.sensorWmm), h = Number(opts.sensorHmm);
    var px = Number(opts.pixelUm);
    if (!(f > 0) || !(w > 0) || !(h > 0)) return null;
    var fovW = 2 * Math.atan(w / (2 * f)) / DEG;
    var fovH = 2 * Math.atan(h / (2 * f)) / DEG;
    var out = {
      fovWDeg: Math.round(fovW * 100) / 100,
      fovHDeg: Math.round(fovH * 100) / 100,
      fovWArcmin: Math.round(fovW * 60),
      fovHArcmin: Math.round(fovH * 60)
    };
    if (px > 0) {
      var scale = 206.265 * px / f;                  // arcsec per pixel
      out.pixelScaleArcsec = Math.round(scale * 100) / 100;
      out.sampling = scale < 1 ? 'oversampled (seeing-limited: bin or shorten)' :
        scale <= 2.5 ? 'well sampled for typical seeing' : 'undersampled (fine for wide field)';
    }
    return out;
  }
  function eyepieceCalc(opts) {
    var f = Number(opts.focalMm), ep = Number(opts.epFocalMm);
    var afov = Number(opts.epAfovDeg) || 50, ap = Number(opts.apertureMm);
    if (!(f > 0) || !(ep > 0)) return null;
    var mag = f / ep;
    var out = {
      magnification: Math.round(mag * 10) / 10,
      trueFovDeg: Math.round(afov / mag * 100) / 100
    };
    if (ap > 0) {
      out.exitPupilMm = Math.round(ap / mag * 10) / 10;
      out.maxUseful = Math.round(ap * 2);
      out.note = mag > ap * 2 ? 'beyond the ~2× per mm aperture ceiling' : '';
    }
    return out;
  }

